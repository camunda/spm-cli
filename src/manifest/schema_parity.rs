//! Parity between the two hand-written descriptions of `ai.json`: the JSON
//! schema (`schema/ai.schema.json`, checked by [`crate::schema::validate`]) and
//! the serde model plus its semantic checks ([`Manifest::from_model`]).
//!
//! `Manifest::parse` runs both, so a gap between them hides until one is used
//! without the other: an editor validating against the published schema, or a
//! model check a dependency's nested `ai.json` (which skips the schema) relies
//! on. The model must enforce everything the schema does; it may be stricter
//! only for the semantic rules listed in [`MODEL_ONLY`].
//!
//! The valid corpus is built around a fully-populated manifest written as
//! struct literals (a new model field does not compile until it is set here),
//! and the rejection cases are generated by mutating it node by node, so a new
//! field is covered without editing this file.

use super::*;
use serde_json::{json, Value};
use std::collections::{BTreeMap, BTreeSet};

/// Expected rejections only the model makes, by case group: semantic rules the
/// schema does not express. Every case of a listed group must diverge exactly
/// this way (schema accepts, model rejects), and a group with no such case is a
/// stale entry — both fail the parity test.
const MODEL_ONLY: &[(&str, &str)] = &[
    (
        "dep-name",
        "`DepName`: names become directory components, so path separators, `.`/`..`, \
         Windows-invalid characters, trailing dots/spaces and device names are rejected",
    ),
    (
        "duplicate-name",
        "a key repeated in one map is collapsed last-wins by a JSON parser before the \
         schema sees it; only the model's streaming deserializer sees both",
    ),
    (
        "name-collision",
        "skills and plugins share one name namespace: uniqueness across two maps",
    ),
    (
        "version-requirement",
        "a `version` must parse as a semver requirement",
    ),
    (
        "path-escape",
        "a `path` must stay inside the repo: no absolute path, no `..` component",
    ),
    (
        "source-pattern",
        "an `allowedSources` entry must parse as `host/org/repo`, `host/org/*`, \
         `host/*` or `file://*`",
    ),
];

const SHA: &str = "0123456789abcdef0123456789ABCDEF01234567";

fn schema() -> Value {
    serde_json::from_str(crate::schema::SOURCE).unwrap()
}

/// A spec with every field set (and so more than one selector: not valid).
fn full_spec() -> SkillSpec {
    SkillSpec {
        git: "https://github.com/org/skills".into(),
        tag: Some("v1.0.0".into()),
        branch: Some("main".into()),
        commit: Some(SHA.into()),
        range: Some(">=1.2, <2".into()),
        path: Some("skills/a".into()),
    }
}

/// One valid spec per version selector of [`full_spec`].
fn selector_specs() -> Vec<SkillSpec> {
    let full = full_spec();
    let bare = SkillSpec {
        tag: None,
        branch: None,
        commit: None,
        range: None,
        ..full.clone()
    };
    vec![
        SkillSpec {
            tag: full.tag.clone(),
            ..bare.clone()
        },
        SkillSpec {
            branch: full.branch.clone(),
            path: None,
            ..bare.clone()
        },
        SkillSpec {
            commit: full.commit.clone(),
            ..bare.clone()
        },
        SkillSpec {
            range: full.range.clone(),
            ..bare
        },
    ]
}

/// A valid manifest with every field set to a non-default value.
fn full_manifest() -> Manifest {
    let deps = |kind: DependencyKind| {
        selector_specs()
            .into_iter()
            .enumerate()
            .map(|(i, s)| (crate::ids::dep(&format!("{kind}-{i}")), s))
            .collect()
    };
    Manifest {
        schema: Some("./schema/ai.schema.json".into()),
        targets: crate::schema::targets().unwrap(),
        resolve_transitive: true,
        allowed_sources: Some(vec![
            "github.com/org/skills".into(),
            "github.com/org/*".into(),
            "gitlab.com/*".into(),
            "file://*".into(),
        ]),
        skills: deps(DependencyKind::Skill),
        plugins: deps(DependencyKind::Plugin),
    }
}

fn to_value<T: Serialize>(v: &T) -> Value {
    serde_json::to_value(v).unwrap()
}

fn keys(v: &Value) -> BTreeSet<String> {
    v.as_object().unwrap().keys().cloned().collect()
}

/// The model and the schema declare the same fields, at the root and in a
/// dependency spec: a fully-populated model serializes exactly the schema's
/// `properties`.
#[test]
fn model_and_schema_declare_the_same_fields() {
    let schema = schema();
    assert_eq!(
        keys(&to_value(&full_manifest())),
        keys(&schema["properties"]),
        "root fields"
    );
    assert_eq!(
        keys(&to_value(&full_spec())),
        keys(&schema["definitions"]["skill"]["properties"]),
        "dependency spec fields"
    );
}

fn schema_verdict(text: &str) -> Result<()> {
    crate::schema::validate(&serde_json::from_str(text)?)
}

fn model_verdict(text: &str) -> Result<Manifest> {
    Manifest::from_model(text, Path::new(MANIFEST_FILE))
}

/// A manifest with `skills: {name: spec}`.
fn with_skill(name: &str, spec: Value) -> String {
    json!({"targets": ["claude"], "skills": {name: spec}}).to_string()
}

fn with_spec(spec: Value) -> String {
    with_skill("a", spec)
}

fn valid_corpus() -> Vec<String> {
    let mut corpus = vec![
        full_manifest().to_text().unwrap(),
        json!({"targets": ["claude"]}).to_string(),
        json!({"targets": ["claude", "copilot"], "resolveTransitive": false,
               "allowedSources": [], "skills": {}, "plugins": {}})
        .to_string(),
        json!({"$schema": "", "targets": ["claude"]}).to_string(),
        with_spec(json!({"git": "u", "commit": SHA.to_lowercase()})),
        with_spec(json!({"git": "git@github.com:org/r.git", "tag": "1.2", "path": "."})),
        with_spec(json!({"git": "file:///srv/r", "branch": "feat/x", "path": "./a/b"})),
        json!({"targets": ["claude"], "allowedSources": ["github.com/org/repo.git"]}).to_string(),
    ];
    for t in crate::schema::targets().unwrap() {
        corpus.push(json!({ "targets": [t] }).to_string());
    }
    for v in ["^1.2", "~1.4.0", "1.2", "=1.0.0-rc.1", "*"] {
        corpus.push(with_spec(json!({"git": "u", "version": v})));
    }
    for name in [
        "a.b",
        "0p",
        "with space",
        "ñandú",
        "_",
        "-x",
        "con-x",
        "com0",
    ] {
        corpus.push(with_skill(name, json!({"git": "u", "tag": "v1"})));
    }
    corpus
}

/// The default-valued fields the model writes or omits on save regardless of
/// the input, dropped before comparing a manifest with its saved form.
fn without_defaults(mut v: Value) -> Value {
    let obj = v.as_object_mut().unwrap();
    for (key, default) in [
        ("resolveTransitive", json!(false)),
        ("skills", json!({})),
        ("plugins", json!({})),
    ] {
        if obj.get(key) == Some(&default) {
            obj.remove(key);
        }
    }
    v
}

/// Every valid manifest passes both layers, and saving the model writes back
/// the same document (no field is dropped or altered) that still passes the
/// schema.
#[test]
fn valid_corpus_is_accepted_by_both_layers_and_round_trips() {
    for text in valid_corpus() {
        schema_verdict(&text).unwrap_or_else(|e| panic!("schema rejects {text}: {e:#}"));
        let model = model_verdict(&text).unwrap_or_else(|e| panic!("model rejects {text}: {e:#}"));
        let saved = model.to_text().unwrap();
        schema_verdict(&saved).unwrap_or_else(|e| panic!("schema rejects saved {saved}: {e:#}"));
        assert_eq!(
            without_defaults(serde_json::from_str(&saved).unwrap()),
            without_defaults(serde_json::from_str(&text).unwrap()),
            "saving {text} changed it"
        );
    }
}

struct Case {
    /// The mutation kind or hand-written rule; [`MODEL_ONLY`] is keyed by it.
    group: &'static str,
    /// What was mutated, for the failure report.
    detail: String,
    text: String,
}

/// JSON pointer escaping of one reference token.
fn token(key: &str) -> String {
    key.replace('~', "~0").replace('/', "~1")
}

/// The JSON pointer of every node of `v`, the root (`""`) included.
fn pointers(v: &Value, at: String, out: &mut Vec<String>) {
    match v {
        Value::Object(map) => {
            for (k, child) in map {
                pointers(child, format!("{at}/{}", token(k)), out);
            }
        }
        Value::Array(items) => {
            for (i, child) in items.iter().enumerate() {
                pointers(child, format!("{at}/{i}"), out);
            }
        }
        _ => {}
    }
    out.push(at);
}

fn json_type(v: &Value) -> &'static str {
    match v {
        Value::Null => "null",
        Value::Bool(_) => "boolean",
        Value::Number(_) => "number",
        Value::String(_) => "string",
        Value::Array(_) => "array",
        Value::Object(_) => "object",
    }
}

/// The version selectors, as the schema's `oneOf` names them.
fn schema_selectors() -> Vec<String> {
    schema()["definitions"]["skill"]["oneOf"]
        .as_array()
        .unwrap()
        .iter()
        .map(|branch| branch["required"][0].as_str().unwrap().to_string())
        .collect()
}

/// Rejection candidates generated from the fully-populated manifest: at every
/// node, each kind of mutation that applies to it.
fn generated_cases() -> Vec<Case> {
    let base = to_value(&full_manifest());
    let full_spec = to_value(&full_spec());
    let selectors = schema_selectors();
    let mut ptrs = Vec::new();
    pointers(&base, String::new(), &mut ptrs);

    let mut cases = Vec::new();
    let mut push = |group, detail: String, v: Value| {
        cases.push(Case {
            group,
            detail,
            text: v.to_string(),
        })
    };
    for ptr in &ptrs {
        let node = base.pointer(ptr).unwrap();
        let mutate = |f: &dyn Fn(&mut Value)| {
            let mut v = base.clone();
            f(v.pointer_mut(ptr).unwrap());
            v
        };
        for sample in [
            json!(null),
            json!(true),
            json!(1),
            json!("x"),
            json!([]),
            json!({}),
        ] {
            if json_type(&sample) != json_type(node) {
                let detail = format!("{ptr} = {sample}");
                push("wrong-type", detail, mutate(&|n| *n = sample.clone()));
            }
        }
        match node {
            Value::Object(map) => {
                push(
                    "unknown-key",
                    format!("{ptr}/x-unknown"),
                    mutate(&|n| {
                        n.as_object_mut()
                            .unwrap()
                            .insert("x-unknown".into(), json!("x"));
                    }),
                );
                for key in map.keys() {
                    push(
                        "missing-key",
                        format!("{ptr}/{}", token(key)),
                        mutate(&|n| {
                            n.as_object_mut().unwrap().remove(key);
                        }),
                    );
                }
                if map.contains_key("git") {
                    for sel in selectors.iter().filter(|s| !map.contains_key(*s)) {
                        push(
                            "selector-conflict",
                            format!("{ptr} + {sel}"),
                            mutate(&|n| {
                                n[sel] = full_spec[sel].clone();
                            }),
                        );
                    }
                }
            }
            Value::Array(items) if !items.is_empty() => {
                push("empty-array", ptr.clone(), mutate(&|n| *n = json!([])));
                push(
                    "duplicate-item",
                    ptr.clone(),
                    mutate(&|n| {
                        let first = n[0].clone();
                        n.as_array_mut().unwrap().push(first);
                    }),
                );
            }
            Value::String(_) => {
                push("empty-string", ptr.clone(), mutate(&|n| *n = json!("")));
            }
            _ => {}
        }
    }
    cases
}

/// Rejection candidates for the value rules the generic mutations can't
/// produce: enum members, string shapes, names, and duplicate keys (which only
/// exist in raw text, never in a `Value`).
fn hand_cases() -> Vec<Case> {
    let dep = json!({"git": "u", "tag": "v1"});
    let mut cases = Vec::new();
    let mut push = |group, detail: &str, text: String| {
        cases.push(Case {
            group,
            detail: detail.to_string(),
            text,
        })
    };
    for t in ["bogus", "Claude", " claude"] {
        push("unknown-target", t, json!({ "targets": [t] }).to_string());
    }
    for c in [
        SHA[..39].to_string(),
        format!("{SHA}0"),
        "g".repeat(40),
        format!("../{}", &SHA[3..]),
    ] {
        push(
            "commit-shape",
            &c,
            with_spec(json!({"git": "u", "commit": c})),
        );
    }
    push(
        "positional-spec",
        "spec as an array",
        with_spec(json!(["u", "v1"])),
    );
    push(
        "positional-manifest",
        "manifest as an array",
        json!([["claude"]]).to_string(),
    );
    for name in [
        "", ".", "..", "a/b", "a\\b", "a:b", "a*b", "a?b", "a\u{1}b", "con", "aux.txt", "LPT1",
        "dot.", "space ",
    ] {
        push("dep-name", name, with_skill(name, dep.clone()));
        let plugin = json!({"targets": ["claude"], "plugins": {name: dep}});
        push("dep-name", name, plugin.to_string());
    }
    let d = r#"{"git":"u","tag":"v1"}"#;
    for map in ["skills", "plugins"] {
        push(
            "duplicate-name",
            map,
            format!(r#"{{"targets":["claude"],"{map}":{{"a":{d},"a":{d}}}}}"#),
        );
    }
    push(
        "name-collision",
        "a",
        json!({"targets": ["claude"], "skills": {"a": dep}, "plugins": {"a": dep}}).to_string(),
    );
    for v in ["not-a-version", "^v1.2", "1.2.3.4", ">=1.2 <<2"] {
        push(
            "version-requirement",
            v,
            with_spec(json!({"git": "u", "version": v})),
        );
    }
    for p in ["/abs", "..", "../up", "a/../../b"] {
        push(
            "path-escape",
            p,
            with_spec(json!({"git": "u", "tag": "v1", "path": p})),
        );
    }
    for s in [
        "github.com",
        "https://github.com/org",
        "*/org",
        "github.com/*/repo",
        "github.com/org*",
    ] {
        push(
            "source-pattern",
            s,
            json!({"targets": ["claude"], "allowedSources": [s]}).to_string(),
        );
    }
    cases
}

/// Over every generated and hand-written case, the schema and the model reach
/// the same verdict — except where [`MODEL_ONLY`] documents that the model is
/// legitimately stricter.
#[test]
fn schema_and_model_agree_on_every_case() {
    let generated = generated_cases();
    let kinds: BTreeSet<_> = generated.iter().map(|c| c.group).collect();
    for kind in [
        "wrong-type",
        "unknown-key",
        "missing-key",
        "selector-conflict",
        "empty-array",
        "duplicate-item",
        "empty-string",
    ] {
        assert!(kinds.contains(kind), "no `{kind}` case was generated");
    }

    let mut failures = Vec::new();
    let mut diverged: BTreeMap<&str, usize> = BTreeMap::new();
    for case in generated.iter().chain(&hand_cases()) {
        let schema = schema_verdict(&case.text);
        let model = model_verdict(&case.text);
        let listed = MODEL_ONLY.iter().any(|(group, _)| *group == case.group);
        let what = format!("[{}] {} — {}", case.group, case.detail, case.text);
        match (&schema, &model) {
            (Ok(()), Err(_)) if listed => *diverged.entry(case.group).or_default() += 1,
            _ if listed => failures.push(format!(
                "{what}: listed in MODEL_ONLY, but schema {} and model {}",
                verdict(&schema),
                verdict(&model)
            )),
            (Ok(()), Err(e)) => failures.push(format!("{what}: only the model rejects: {e:#}")),
            (Err(e), Ok(_)) => failures.push(format!("{what}: only the schema rejects: {e:#}")),
            _ => {}
        }
    }
    for (group, _) in MODEL_ONLY {
        if !diverged.contains_key(group) {
            failures.push(format!(
                "stale MODEL_ONLY entry `{group}`: no case diverges"
            ));
        }
    }
    assert!(failures.is_empty(), "\n{}", failures.join("\n"));
}

fn verdict<T>(r: &Result<T>) -> &'static str {
    if r.is_ok() {
        "accepts"
    } else {
        "rejects"
    }
}
